				O método de ensino da Escola de Educação Infantil Pequeno Príncipe e Pequena Princesa é norteado pelos materiais didáticos SER e Pocket’s (Pearson Longman), além de ser complementado por diversas atividades gráficas e lúdicas, desenvolvidas pela equipe pedagógica da escola. O foco deste trabalho tem base nos conteúdos previstos e objetivos esperados. <br><br>
Os alunos da escola têm diariamente, a partir dos 3 anos de idade, além das atividades pedagógicas, as aulas de inglês, o que facilita a aprendizagem do segundo idioma. 
O material didático utilizado na escola (Ser - Abril Educação)  entende a aprendizagem da criança como uma ampla relação do professor e aluno, com ponto de partida na valorização dos conhecimentos do aluno, do respeito aos seus interesses e da oportunidade dele tentar novas experiências. <br><br>
As atividades pedagógicas orientam para a construção da identidade pessoal, explorando atitudes, regras e sentimentos, com o objetivo de desenvolver o respeito, as diferenças e a responsabilidade em cada ser. Elas exploram as diferentes linguagens: corporal, visual, plástica, musical, oral, escrita e matemática. <br><br>
Todas as unidades temáticas são estruturadas nos eixos do conhecimento, tendo como eixo central a Sociedade e Inter-relação com a Natureza, uma vez que as necessidades humanas, as interações com a natureza e a ação transformadora do homem definem e explicam a vida humana e constroem a identidade do ser histórico social. O eixo central vem subdividido nos eixos do conhecimento, como a Linguagem oral e escrita, a Matemática, Natureza e Sociedade, Música, Arte e Movimento. <br><br>
O método da escola destaca-se ainda por proporcionar à criança, desde a infância, o contato com a língua inglesa, com atividades realizadas em sala ambiente, utilizando material impresso apropriado, literatura infantil em inglês (complementar), sonorização, música, vídeos, jogos, brinquedos pedagógicos da língua estrangeira e outros materiais que beneficiam esta aprendizagem. Assim, o diálogo e a livre expressão caracterizam o método com a língua inglesa.  <br><br>
Há também as aulas diversificadas como o ballet e a música, que também são trabalhadas em sala ambiente, tendo o suporte de acessórios e materiais necessários e privilegiando a participação, a autonomia, a linguagem e a livre expressão da criança.
